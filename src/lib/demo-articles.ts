function item(
  id: string,
  slug: string,
  title: string,
  excerpt: string,
  category: string,
  hours: number,
  image: string,
  lead = false,
): DemoArticle {
  return {
    id,
    title,
    slug,
    excerpt,
    body: BODIES[category] || BODIES.analysis,
    category_slug: category,
    image_url: image,
    image_caption: "সম্পাদকীয় ভিজ্যুয়াল — নমুনা",
    author_name: "ক্রীড়া ডেস্ক",
    published_at: hoursAgo(hours),
    is_lead: lead,
    is_featured: lead || hours < 12,
    public_id: id.replace(/-/g, "").slice(0, 12),
    tags: [category, "খেলাটিভি"],
    content_type: "news",
    youtube_url: null,
    image_urls: [image],
  };
}

