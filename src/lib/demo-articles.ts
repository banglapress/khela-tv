export function demoFind(rawKey: string): DemoArticle | null {
  const key = decodeURIComponent(rawKey || "").trim();
  return DEMO_ARTICLES.find((row) => row.slug === key || row.public_id === key || row.id === key) ?? null;
}

export function demoByCategory(slug: string): DemoArticle[] {
  const children: Record<string, string[]> = {
    cricket: ["cricket", "cricket-bangladesh", "cricket-international", "ipl", "bpl"],
    football: ["football", "football-bangladesh", "football-international"],
  };
  const slugs = children[slug] || [slug];
  return DEMO_ARTICLES.filter((row) => slugs.includes(row.category_slug));
}

export function demoSearch(term: string): DemoArticle[] {
  const q = term.trim().toLowerCase();
  if (!q) return [];
  return DEMO_ARTICLES.filter((row) => `${row.title} ${row.excerpt}`.toLowerCase().includes(q));
}
